"""Build side-by-side RGB + alpha H.264 videos, preserving source fps and duration.
Requires imageio-ffmpeg. Original transparent WebM files remain in resources/mobile-pet.
"""
import hashlib
import json
import pathlib
import re
import subprocess
import imageio_ffmpeg

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'resources/mobile-pet/dsh-source'
OUTPUT = ROOT / 'apps/call-phone-uni/src/static/mobile-pet/video'


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    clips = json.loads((SOURCE / 'clips.json').read_text())
    config = (SOURCE / 'config.jsonc').read_text()
    config = re.sub(r'"(?:\\.|[^"\\])*"|//[^\n]*|/\*.*?\*/', lambda m: m[0] if m[0].startswith('"') else '', config, flags=re.S)
    config = json.loads(re.sub(r',\s*([}\]])', r'\1', config))
    weights = {}
    for category in config['animations']['categories']:
        for name in category['actions']: weights[name] = category['weight'] / len(category['actions'])
    for pool, key in [('idle', 'idle'), ('turn', 'turn')]:
        names = config['animations'][pool]
        for name in names: weights[name] = config['animationWeights'][key] / len(names)
    moves = config['animations']['moves']['actions']
    for item in moves: weights[item['name']] = config['animationWeights']['move'] / len(moves)
    bounds = json.loads((SOURCE / 'bounds.json').read_text())
    actions = []
    wanted = {clip[0] + '.mp4' for clip in clips}
    for old in OUTPUT.glob('*.mp4'):
        if old.name not in wanted: old.unlink()
    for id_, label, original, group in clips:
        source = SOURCE / (id_ + '.webm')
        # Preserve the entire original video viewport; square padding never cuts off props.
        graph = '[0:v]pad=640:640:0:140:color=black@0,split=2[rgb][mask];[rgb]format=yuv420p[c];[mask]alphaextract,format=yuv420p[a];[c][a]hstack=inputs=2[out]'
        subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(), '-v', 'error', '-y', '-c:v', 'libvpx-vp9',
                        '-i', str(source), '-filter_complex', graph, '-map', '[out]', '-an',
                        '-c:v', 'libx264', '-crf', '18', '-preset', 'medium', '-pix_fmt', 'yuv420p',
                        '-movflags', '+faststart', str(OUTPUT / (id_ + '.building.mp4'))], check=True)
        (OUTPUT / (id_ + '.building.mp4')).replace(OUTPUT / (id_ + '.mp4'))
        actions.append(dict(id=id_, label=label, group=group, video=f'/static/mobile-pet/video/{id_}.mp4',
                            repeats=0 if id_ == 'idle' else 1, randomWeight=weights.get(original, 0), bounds=bounds[id_]))
    (OUTPUT / 'catalog.json').write_text(json.dumps(dict(format='rgb-alpha-sbs-v1', crop=[0,-140,640,500], actions=actions), ensure_ascii=False, indent=2)+'\n')
    (ROOT / 'apps/call-phone-uni/src/modules/mobile-pet/appearance.ts').write_text(
        '// Generated by scripts/convert-dsh-video.py. Source and license: resources/mobile-pet/dsh-source.\n' +
        'export type PetVideoAction = { id: string; label: string; group: string; video: string; repeats: number; randomWeight: number; bounds: number[] };\n' +
        'export const petActions: PetVideoAction[] = ' + json.dumps(actions, ensure_ascii=False, indent=2) + ';\n')
    print('Converted',len(actions),'videos, retaining source frame rate; bytes:',sum(p.stat().st_size for p in OUTPUT.glob('*.mp4')))


if __name__ == '__main__': main()
