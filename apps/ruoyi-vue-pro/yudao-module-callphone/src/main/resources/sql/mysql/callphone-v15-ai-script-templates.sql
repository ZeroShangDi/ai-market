-- Versioned local sales scripts. Content is encrypted and immutable once published.
CREATE TABLE IF NOT EXISTS `cp_ai_script_template` (
  `id` bigint NOT NULL,
  `tenant_id` bigint NOT NULL DEFAULT 0,
  `template_key` char(32) NOT NULL,
  `version_no` int unsigned NOT NULL,
  `name` varchar(80) NOT NULL,
  `stage_code` varchar(32) DEFAULT NULL,
  `channel` varchar(24) NOT NULL,
  `tags_json` varchar(1024) NOT NULL DEFAULT '[]',
  `content_ciphertext` text NOT NULL,
  `variables_json` varchar(1200) NOT NULL DEFAULT '[]',
  `status` varchar(16) NOT NULL DEFAULT 'draft',
  `usage_count` int unsigned NOT NULL DEFAULT 0,
  `copy_count` int unsigned NOT NULL DEFAULT 0,
  `last_used_at` datetime(3) DEFAULT NULL,
  `created_by` bigint NOT NULL,
  `published_by` bigint DEFAULT NULL,
  `published_at` datetime(3) DEFAULT NULL,
  `creator` varchar(64) DEFAULT '',
  `create_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updater` varchar(64) DEFAULT '',
  `update_time` datetime(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  `deleted` bit(1) NOT NULL DEFAULT b'0',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_cp_ai_script_tenant_key_version` (`tenant_id`,`template_key`,`version_no`),
  KEY `idx_cp_ai_script_tenant_status_time` (`tenant_id`,`status`,`update_time`),
  KEY `idx_cp_ai_script_tenant_stage_channel` (`tenant_id`,`stage_code`,`channel`),
  KEY `idx_cp_ai_script_tenant_creator` (`tenant_id`,`created_by`,`create_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='Call Phone 加密话术模板及不可变版本';
