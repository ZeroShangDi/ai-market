"""Rebuild imported DS atlases: pip install pillow imageio-ffmpeg; python3 scripts/convert-dsh-pet.py.
Uses libvpx-vp9 explicitly: FFmpeg's default VP9 decoder discards WebM alpha.
"""
import hashlib
import json
import math
import pathlib
import subprocess
import tempfile

import imageio_ffmpeg
from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'resources/mobile-pet/dsh-source'
OUTPUT = ROOT / 'apps/call-phone-uni/src/modules/mobile-pet/assets/dsh'
FPS, SIZE, COLUMNS = 12, 192, 12


def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    clips = json.loads((SOURCE / 'clips.json').read_text())
    catalog = []
    with tempfile.TemporaryDirectory() as directory:
        tmp = pathlib.Path(directory)
        bounds = None
        for id_, label, original, group in clips:
            target = tmp / id_
            target.mkdir()
            subprocess.run([imageio_ffmpeg.get_ffmpeg_exe(), '-v', 'error', '-c:v', 'libvpx-vp9',
                            '-i', str(SOURCE / (id_ + '.webm')), '-vf', f'fps={FPS}',
                            str(target / '%04d.png')], check=True)
            frames = sorted(target.glob('*.png'))
            if not 1 <= len(frames) <= 256:
                raise ValueError(f'{id_}: invalid frame count {len(frames)}')
            for frame in frames:
                with Image.open(frame) as image:
                    box = image.getchannel('A').point(lambda a: 255 if a > 16 else 0).getbbox()
                    if box:
                        bounds = box if bounds is None else (min(bounds[0], box[0]), min(bounds[1], box[1]), max(bounds[2], box[2]), max(bounds[3], box[3]))
        # One common crop preserves character size and position across ALL clips, including props.
        left, top, right, bottom = bounds
        side = max(right - left, bottom - top) + 12
        cx, cy = (left + right) / 2, (top + bottom) / 2
        crop = (round(cx - side / 2), round(cy - side / 2), round(cx - side / 2) + side, round(cy - side / 2) + side)
        for id_, label, original, group in clips:
            frames = sorted((tmp / id_).glob('*.png'))
            rows = math.ceil(len(frames) / COLUMNS)
            atlas = Image.new('RGBA', (COLUMNS * SIZE, rows * SIZE))
            for i, frame in enumerate(frames):
                with Image.open(frame) as image:
                    atlas.paste(image.crop(crop).resize((SIZE, SIZE), Image.Resampling.LANCZOS), (i % COLUMNS * SIZE, i // COLUMNS * SIZE))
            atlas.save(OUTPUT / (id_ + '.png'), optimize=True)
            catalog.append(dict(id=id_, label=label, group=group, columns=COLUMNS, rows=rows,
                                frames=[dict(cell=i, duration=round((i + 1) * 1000 / FPS) - round(i * 1000 / FPS)) for i in range(len(frames))],
                                repeats=0 if id_ == 'idle' else 1, original=original + '.webm',
                                sourceSha256=hashlib.sha256((SOURCE / (id_ + '.webm')).read_bytes()).hexdigest()))
        (OUTPUT / 'catalog.json').write_text(json.dumps(dict(crop=crop, fps=FPS, size=SIZE, actions=catalog), ensure_ascii=False, indent=2) + '\n')
    imports = '\n'.join(f"import clip{i} from './assets/dsh/{clip['id']}.png';" for i, clip in enumerate(catalog))
    sheets = ',\n'.join(f"  {{ image: clip{i}, columns: {clip['columns']}, rows: {clip['rows']} }}" for i, clip in enumerate(catalog))
    actions = [dict(id=clip['id'], label=clip['label'], group=clip['group'], sheet=i, frames=clip['frames'], repeats=clip['repeats']) for i, clip in enumerate(catalog)]
    (OUTPUT.parent.parent / 'appearance.ts').write_text(
        '// Generated by scripts/convert-dsh-pet.py; source and attribution: resources/mobile-pet/dsh-source.\n' + imports +
        '\n\nexport type PetFrame = { cell: number; duration: number };\n' +
        'export type PetAction = { id: string; label: string; group: string; sheet: number; frames: PetFrame[]; repeats: number };\n' +
        'export const petSheets = [\n' + sheets + '\n];\n' +
        'export const petActions: PetAction[] = ' + json.dumps(actions, ensure_ascii=False, separators=(',', ':')) + ';\n' +
        'export const petFrames = petActions[0].frames;\n')
    print(f'Converted {len(catalog)} transparent animations; shared crop {crop}')


if __name__ == '__main__':
    main()
